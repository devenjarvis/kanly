// The agent integration lets Kanly carry its own instructions: `kanly guide`
// prints the workflow for any coding agent, `kanly init --agent=claude` writes
// it as a Claude Code skill and registers `kanly hook stop`, which runs Kanly
// on the session's changes when the agent stops and hands the llm brief back
// when the score is too low.

const (
	defaultHookMinScore = 80
	defaultHookDiffBase = "origin/main"
	// Claude Code kills a hook after its timeout (seconds). A diff run compiles
	// one schema per changed package, so allow well over the default.
	hookTimeoutSeconds = 900
	// maxHookReason caps the brief handed back to the agent at Claude Code's
	// documented cap on hook output; the agent can re-run the command for all
	// of it.
	maxHookReason = 10000
	skillMarker   = "<!-- Generated by `kanly init`. Re-run it to update; delete this line to keep local edits. -->"
)

// guide.md is the workflow an agent follows. {{command}} is how the agent
// invokes Kanly (`kanly`, `go run ./cmd/kanly`, ...) and {{base}} the ref it
// diffs against.
//
//go:embed guide.md
var guideTemplate string

func guideText(cmd, base string) string {
	return strings.NewReplacer("{{command}}", cmd, "{{base}}", base).Replace(guideTemplate)
}

func skillText(cmd, base string) string {
	return `---
name: kanly
description: Mutation-test Go code with Kanly to check that tests actually catch bugs. Use after writing or changing Go code or tests, before calling the work done, and when asked whether tests are good enough.
---

` + skillMarker + "\n\n" + guideText(cmd, base)
}

// runGuide implements `kanly guide`.
func runGuide(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("kanly guide", flag.ContinueOnError)
	fs.SetOutput(stderr)
	cmd := fs.String("command", "kanly", "how the agent invokes kanly")
	base := fs.String("diff-base", defaultHookDiffBase, "git ref the agent diffs against")
	if err := fs.Parse(args); err != nil || fs.NArg() > 0 {
		fmt.Fprint(stderr, "usage: kanly guide [--command=kanly] [--diff-base=origin/main]\n")
		return 2
	}
	fmt.Fprint(stdout, guideText(*cmd, *base))
	return 0
}

// runInit implements `kanly init --agent=claude`.
func runInit(args []string, stdout, stderr io.Writer) int {
	const usage = "usage: kanly init --agent=claude [--dir=.] [--command=kanly] [--diff-base=origin/main] [--min-score=80] [--no-hook]\n"
	fs := flag.NewFlagSet("kanly init", flag.ContinueOnError)
	fs.SetOutput(stderr)
	agent := fs.String("agent", "", "coding agent to configure: claude")
	dir := fs.String("dir", ".", "project root to write the agent configuration into")
	cmd := fs.String("command", "kanly", "how the agent and the hook invoke kanly, e.g. \"go run ./cmd/kanly\"")
	base := fs.String("diff-base", defaultHookDiffBase, "git ref the hook and the agent diff against")
	minScore := fs.Float64("min-score", defaultHookMinScore, "score including not-covered mutants below which the stop hook hands the brief back")
	noHook := fs.Bool("no-hook", false, "write only the skill, not the stop hook")
	if err := fs.Parse(args); err != nil || fs.NArg() > 0 {
		fmt.Fprint(stderr, usage)
		return 2
	}
	if *agent != "claude" {
		fmt.Fprintf(stderr, "--agent: only claude is supported, got %q\n%s", *agent, usage)
		fmt.Fprint(stderr, "For any other agent, add one line to AGENTS.md: \"Before finishing a Go change, run `kanly guide` and follow it.\"\n")
		return 2
	}
	if *minScore < 0 || *minScore > 100 {
		fmt.Fprintf(stderr, "--min-score: must be between 0 and 100, got %v\n", *minScore)
		return 2
	}

	skillPath := filepath.Join(*dir, ".claude", "skills", "kanly", "SKILL.md")
	wrote, err := writeSkill(skillPath, skillText(*cmd, *base))
	if err != nil {
		fmt.Fprintf(stderr, "kanly init: %v\n", err)
		return 1
	}
	if wrote {
		fmt.Fprintf(stdout, "wrote %s\n", skillPath)
	} else {
		fmt.Fprintf(stdout, "kept %s: it has local edits (no %q line)\n", skillPath, "Generated by `kanly init`")
	}

	if *noHook {
		return 0
	}
	settingsPath := filepath.Join(*dir, ".claude", "settings.json")
	// Hooks run in the session's current directory, which moves with `cd`.
	hookCmd := fmt.Sprintf(`cd "$CLAUDE_PROJECT_DIR" && %s hook stop --diff-base=%s --min-score=%v`, *cmd, *base, *minScore)
	if err := addStopHook(settingsPath, hookCmd); err != nil {
		fmt.Fprintf(stderr, "kanly init: %v\n", err)
		return 1
	}
	fmt.Fprintf(stdout, "registered the stop hook in %s: %s\n", settingsPath, hookCmd)
	return 0
}

// writeSkill writes the skill unless an existing file has dropped the marker
// line, which is how a user keeps local edits.
func writeSkill(path, content string) (bool, error) {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return false, err
	}
	old, err := os.ReadFile(path)
	if err == nil && !bytes.Contains(old, []byte(skillMarker)) {
		return false, nil
	}
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return false, err
	}
	return true, os.WriteFile(path, []byte(content), 0o644)
}

// isKanlyStopHook reports whether a hook command is one `kanly init` wrote.
func isKanlyStopHook(command string) bool {
	return strings.Contains(command, " hook stop")
}

// addStopHook registers command as a Stop hook in a Claude Code settings
// file, keeping everything else in it. A Kanly stop hook already there is
// replaced, so re-running init updates the command instead of adding another.
func addStopHook(path, command string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	settings := map[string]any{}
	data, err := os.ReadFile(path)
	switch {
	case err == nil:
		if err := json.Unmarshal(data, &settings); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
	case !errors.Is(err, fs.ErrNotExist):
		return err
	}

	hooks, ok := settings["hooks"].(map[string]any)
	if !ok {
		if settings["hooks"] != nil {
			return fmt.Errorf("%s: \"hooks\" is not an object", path)
		}
		hooks = map[string]any{}
	}
	groups, ok := hooks["Stop"].([]any)
	if !ok && hooks["Stop"] != nil {
		return fmt.Errorf("%s: \"hooks.Stop\" is not an array", path)
	}

	entry := map[string]any{"type": "command", "command": command, "timeout": hookTimeoutSeconds}
	replaced := false
	for _, g := range groups {
		group, ok := g.(map[string]any)
		if !ok {
			continue
		}
		list, _ := group["hooks"].([]any)
		for i, h := range list {
			if hook, ok := h.(map[string]any); ok {
				if c, _ := hook["command"].(string); isKanlyStopHook(c) {
					list[i] = entry
					replaced = true
				}
			}
		}
	}
	if !replaced {
		groups = append(groups, map[string]any{"hooks": []any{entry}})
	}
	hooks["Stop"] = groups
	settings["hooks"] = hooks

	// People read and edit this file, so && stays && rather than \u0026.
	var out bytes.Buffer
	enc := json.NewEncoder(&out)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	// Values decoded from JSON always encode.
	_ = enc.Encode(settings)
	return os.WriteFile(path, out.Bytes(), 0o644)
}

// stopHookInput is the part of Claude Code's Stop hook input Kanly reads.
type stopHookInput struct {
	// StopHookActive is set when the agent is already continuing because a
	// stop hook blocked it. Kanly blocks once per stop so an agent that cannot
	// reach the score is never trapped; CI stays the hard gate.
	StopHookActive bool `json:"stop_hook_active"`
}

// runHook implements `kanly hook stop`, a Claude Code Stop hook. It runs
// Kanly on the changes since --diff-base and, when the score including
// not-covered mutants is below --min-score, blocks the stop with the llm
// brief as the reason. Arguments after `--` are passed to that run.
func runHook(args []string, stdin io.Reader, stdout, stderr io.Writer) int {
	const usage = "usage: kanly hook stop [--diff-base=origin/main] [--min-score=80] [-- kanly flags and patterns...]\n"
	if len(args) == 0 || args[0] != "stop" {
		fmt.Fprint(stderr, usage)
		return 2
	}
	fs := flag.NewFlagSet("kanly hook stop", flag.ContinueOnError)
	fs.SetOutput(stderr)
	base := fs.String("diff-base", defaultHookDiffBase, "git ref to diff against")
	minScore := fs.Float64("min-score", defaultHookMinScore, "score including not-covered mutants below which the stop is blocked")
	if err := fs.Parse(args[1:]); err != nil {
		fmt.Fprint(stderr, usage)
		return 2
	}

	var in stopHookInput
	if data, err := io.ReadAll(stdin); err == nil && len(bytes.TrimSpace(data)) > 0 {
		if err := json.Unmarshal(data, &in); err != nil {
			fmt.Fprintf(stderr, "kanly hook stop: reading hook input: %v\n", err)
			return 1
		}
	}
	if in.StopHookActive {
		return 0
	}

	runArgs := []string{"--quiet", "--diff", "--diff-base=" + *base, "--fail-fast", "--format=llm", fmt.Sprintf("--min-score=%v", *minScore)}
	runArgs = append(runArgs, fs.Args()...)
	var brief bytes.Buffer
	code := run(runArgs, &brief, stderr)
	switch code {
	case 0:
		return 0
	case 3:
		reason := fmt.Sprintf("Kanly: the Go code changed since %s scores below %v%% (including mutants no test reaches). Work through the brief below before finishing, then re-run its --mutant commands.\n\n%s", *base, *minScore, brief.String())
		reason = truncateReason(reason, maxHookReason, fmt.Sprintf("\n\n[brief truncated; run `kanly --diff --diff-base=%s --format=llm` for all of it]\n", *base))
		// A map of strings always encodes.
		out, _ := json.Marshal(map[string]string{"decision": "block", "reason": reason})
		stdout.Write(append(out, '\n'))
		return 0
	default:
		// Kanly could not test something (exit 1) or was misconfigured (exit
		// 2). Writing tests will not fix either, so report without blocking.
		fmt.Fprintf(stderr, "kanly hook stop: kanly exited %d; not blocking\n", code)
		return 1
	}
}

// truncateReason cuts s to at most limit bytes, without splitting a UTF-8
// sequence, and appends note when it cut anything.
func truncateReason(s string, limit int, note string) string {
	if len(s) <= limit {
		return s
	}
	return strings.ToValidUTF8(s[:limit], "") + note
}
